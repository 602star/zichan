import { writeFile, mkdir } from 'node:fs/promises';

// Refresh at build/development time only. The application never contacts this source.
const repository = 'NateScarlet/holiday-cn';
const lastYear = Number(process.argv[2] ?? new Date().getUTCFullYear() + 1);
if (!Number.isInteger(lastYear) || lastYear < 2007 || lastYear > 2099) throw new Error('expected final year 2007–2099');
let sha = process.argv[3];
if (!sha) {
  const response = await fetch(`https://api.github.com/repos/${repository}/commits/master`);
  if (!response.ok) throw new Error(`holiday source: ${response.status}`);
  sha = (await response.json()).sha;
}
if (!/^[a-f0-9]{40}$/.test(sha)) throw new Error('expected a fixed source commit');
const years = Array.from({ length: lastYear - 2007 + 1 }, (_, i) => 2007 + i);
const bundles = await Promise.all(years.map(async (year) => {
  const result = await fetch(`https://raw.githubusercontent.com/${repository}/${sha}/${year}.json`);
  if (!result.ok) throw new Error(`holiday ${year}: ${result.status}`);
  const data = await result.json();
  if (data.year !== year || !Array.isArray(data.days) || !Array.isArray(data.papers)) throw new Error(`invalid holiday ${year}`);
  return data;
}));
const entries = bundles.flatMap(bundle => bundle.days.map(day => [day.date, day.name, day.isOffDay]));
const covered = bundles.filter(bundle => bundle.papers.length > 0).map(bundle => bundle.year);
const source = `// Generated by scripts/calendar/update-holidays.mjs. MIT: ${repository}@${sha}\n`
  + `export const HOLIDAY_SOURCE = ${JSON.stringify({ repository, commit: sha, papers: [...new Set(bundles.flatMap(bundle => bundle.papers))] })} as const;\n`
  + `export const HOLIDAY_YEARS: readonly number[] = ${JSON.stringify(covered)};\n`
  + `export const HOLIDAY_DAYS: readonly (readonly [string, string, boolean])[] = ${JSON.stringify(entries)};\n`;
await writeFile(new URL('../../packages/core/src/calendar-holidays.ts', import.meta.url), source);
const license = await fetch(`https://raw.githubusercontent.com/${repository}/${sha}/LICENSE`);
if (!license.ok) throw new Error('holiday license unavailable');
await mkdir(new URL('../../apps/web/public/licenses/', import.meta.url), { recursive: true });
await writeFile(new URL('../../apps/web/public/licenses/holiday-cn.txt', import.meta.url), await license.text());
console.log(JSON.stringify({ commit: sha, covered, days: entries.length }));
