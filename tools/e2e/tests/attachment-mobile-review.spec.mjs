import { test, expect } from './fixtures.mjs';
import { entry, receipt, addAndExtract, ORDER } from './local-order-helpers.mjs';
import { openLedgerSection } from '../ledger-navigation.mjs';

test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Shanghai' });
test.setTimeout(180_000);

test('fresh entry leaves old attachments available and setting opts into automatic recovery', async ({ page }) => {
  const form = await entry(page);
  const image = await receipt(page);
  await form.getByLabel(/^金额/).fill('18.80');
  await form.getByLabel('附件 / 图片', { exact: true }).setInputFiles(image);
  await form.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '保留草稿并关闭', exact: true }).click();
  const newEntry = page.locator('#transaction-records').getByRole('button', { name: /^\+ 记(账|支出)$/ });
  await newEntry.click();
  await expect(form.getByLabel(/^金额/)).toHaveValue('');
  await expect(form.locator('.zc-attachment-item')).toHaveCount(0);
  await expect(form.getByLabel('附件 / 图片', { exact: true })).toBeEnabled();
  await form.getByLabel('附件 / 图片', { exact: true }).setInputFiles({ ...image, name: 'new-receipt.png' });
  await expect(form.locator('.zc-attachment-item')).toHaveCount(1);
  await form.locator('.zc-entry-draft-list > summary').click();
  await form.getByRole('button', { name: '恢复这份草稿', exact: true }).click();
  await expect(form.getByLabel(/^金额/)).toHaveValue('18.80');
  await expect(form.getByText(image.name, { exact: true })).toBeVisible();
  await form.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '保留草稿并关闭', exact: true }).click();
  await openLedgerSection(page, 'settings', 'ledger');
  const preference = page.getByRole('checkbox', { name: '新建记账时自动恢复最近草稿', exact: true });
  await expect(preference).not.toBeChecked(); await preference.check();
  await page.reload(); await openLedgerSection(page, 'settings', 'ledger');
  await expect(preference).toBeChecked();
  await openLedgerSection(page, 'transactions', 'records'); await newEntry.click();
  await expect(form.getByLabel(/^金额/)).toHaveValue('18.80');
  await expect(form.getByText(image.name, { exact: true })).toBeVisible();
  await form.locator('.zc-entry-draft-list > summary').click();
  await expect(form.locator('.zc-entry-draft-list')).toContainText('附件 1 个');
  await form.getByRole('button', { name: '恢复这份草稿', exact: true }).click();
  await expect(form.getByText('new-receipt.png', { exact: true })).toBeVisible();
  await expect(form.getByLabel(/^金额/)).toHaveValue('');
});

test('mobile review edits fields, preserves corrections through OCR retry, and shows number source without changing masks', async ({ page, context }) => {
  const form = await entry(page);
  const panel = await addAndExtract(page, form, await receipt(page));
  const child = page.getByRole('dialog', { name: '附件处理', exact: true });
  await expect(panel.getByRole('tab', { name: '核对信息', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(panel.getByLabel('附件保留与隐私', { exact: true })).toBeHidden();
  await expect(panel.getByLabel('订单号候选', { exact: true })).toBeHidden();
  await panel.getByLabel('实付金额候选', { exact: true }).fill('39.80');
  await panel.getByLabel('交易时间候选', { exact: true }).fill('12:34:56');
  await panel.locator('summary').filter({ hasText: /^补充字段/ }).click();
  const merchant = panel.getByLabel('交易对象 / 商家候选', { exact: true });
  await merchant.pressSequentially('Manual store');
  await expect(merchant).toHaveValue('Manual store'); await expect(merchant).toBeFocused();
  await panel.locator('summary').filter({ hasText: /^补充字段/ }).click();
  await panel.locator('summary').filter({ hasText: /^订单信息/ }).click();
  await expect(panel.getByLabel('订单号候选', { exact: true })).toHaveValue(ORDER);
  const orderRow = panel.locator('.zc-attachment-review-field').filter({ has: page.getByLabel('订单号候选', { exact: true }) });
  await orderRow.getByRole('button', { name: '查看依据', exact: true }).click();
  await expect(panel.getByRole('img', { name: '订单号原图局部', exact: true })).toBeVisible();
  await expect.poll(() => panel.getByRole('img', { name: '订单号原图局部', exact: true }).evaluate((node) => node.width)).toBeGreaterThan(300);
  await panel.getByRole('button', { name: '收起依据', exact: true }).click();
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await orderRow.getByRole('button', { name: '复制订单号', exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(ORDER);
  await panel.getByLabel('订单号候选', { exact: true }).fill('000012349999');
  await panel.locator('.zc-attachment-file-tools > summary').click();
  await panel.getByRole('button', { name: '重新提取', exact: true }).click();
  await expect(panel.locator('.zc-attachment-file-tools > summary')).toHaveText('图片信息与重新提取', { timeout: 120_000 });
  await expect(panel.getByLabel('实付金额候选', { exact: true })).toHaveValue('39.80');
  await expect(panel.getByLabel('交易时间候选', { exact: true })).toHaveValue('12:34:56');
  await expect(panel.getByLabel('订单号候选', { exact: true })).toHaveValue('000012349999');
  await panel.locator('.zc-attachment-file-tools > summary').click();
  await panel.locator('summary').filter({ hasText: /^订单信息/ }).click();
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await child.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`review-info-${width}.png`) });
  }
  await child.getByRole('button', { name: '下一步：核对图片', exact: true }).click();
  const privacy = panel.getByRole('region', { name: '附件隐私核对', exact: true });
  await privacy.getByRole('checkbox', { name: '已检查整张图片并确认隐私遮盖', exact: true }).check();
  await panel.getByRole('tab', { name: '核对信息', exact: true }).click();
  await expect(panel.getByLabel('实付金额候选', { exact: true })).toHaveValue('39.80');
  await panel.getByLabel('实付金额候选', { exact: true }).fill('abc');
  await child.getByRole('button', { name: '确认并应用', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('请填写大于零的金额');
  await panel.getByLabel('实付金额候选', { exact: true }).fill('39.80');
  await panel.getByRole('tab', { name: /^图片与隐私/ }).click();
  await expect(privacy.getByRole('checkbox', { name: '已检查整张图片并确认隐私遮盖', exact: true })).toBeChecked();
  await child.getByRole('button', { name: '确认并应用', exact: true }).click();
  await expect(child).toBeHidden();
  await expect(form.getByLabel(/^金额/)).toHaveValue('39.80');
  await form.getByRole('button', { name: '字段模式：完整', exact: true }).click();
  await expect(form.getByLabel('订单号', { exact: true })).toHaveValue('000012349999');
  await expect(form.getByLabel('备注', { exact: true })).toHaveValue('');
});
