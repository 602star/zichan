import { test, expect } from './fixtures.mjs';
import { openLedger } from './helpers.mjs';

test.use({ viewport: { width: 1280, height: 900 }, timezoneId: 'Asia/Shanghai' });
test.setTimeout(180_000);
const go = (page, screen, tab) => page.evaluate((detail) => window.dispatchEvent(new CustomEvent('zichan:navigate', { detail })), { screen, tab });
const bills = (page) => page.locator('.zc-sidebar [data-destination="bills"] .zc-sidebar-nav-item');
const records = (page) => page.locator('.zc-sidebar [data-destination="records"] .zc-sidebar-nav-item');
const planForm = (page) => page.getByRole('dialog', { name: '新增 · 账单计划', exact: true });

test('bills and repayments work without account setup, and marking never duplicates spending', async ({ page }) => {
  page.setDefaultTimeout(12_000);
  await page.clock.setFixedTime(new Date('2026-01-31T11:00:00+08:00'));
  await openLedger(page);
  await bills(page).click();
  await expect(page.locator('h1')).toHaveText('账单与还款');
  await page.getByRole('group', { name: '常用账单类型' }).getByRole('button', { name: '信用卡还款', exact: true }).click();
  let form = planForm(page);
  await expect(form.getByLabel(/^名称/)).toHaveValue('信用卡还款');
  await expect(form.getByRole('combobox', { name: '账户', exact: true })).toHaveCount(0);
  await form.getByLabel(/^金额/).fill('1800.25');
  await form.getByLabel('频率', { exact: true }).selectOption('once');
  await form.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toBeHidden();
  let row = page.getByRole('row').filter({ has: page.getByRole('cell', { name: '信用卡还款', exact: true }) }).filter({ has: page.getByRole('button', { name: '仅标记已处理', exact: true }) });
  await row.getByRole('button', { name: '仅标记已处理', exact: true }).click();
  await expect(row).toContainText('计划已完成');
  await expect(row.getByRole('button', { name: '登记流水', exact: true })).toBeDisabled();
  const undo = page.getByRole('status').filter({ hasText: '本期已处理，未生成收支流水' });
  await undo.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(row).not.toContainText('计划已完成');
  await row.getByRole('button', { name: '仅标记已处理', exact: true }).click();
  await expect(row).toContainText('计划已完成');
  await records(page).click();
  await expect(page.locator('.zc-transaction-row')).toHaveCount(0);
  await bills(page).click();
  await page.getByRole('group', { name: '常用账单类型' }).getByRole('button', { name: '分期付款', exact: true }).click();
  form = planForm(page);
  await form.getByLabel(/^金额/).fill('200.10');
  await form.getByLabel(/^总期数/).fill('3');
  await form.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toBeHidden();
  row = page.getByRole('row').filter({ has: page.getByRole('cell', { name: '分期付款', exact: true }) }).filter({ has: page.getByRole('button', { name: '仅标记已处理', exact: true }) });
  await row.getByRole('button', { name: '登记流水', exact: true }).click();
  await expect(row).toContainText('2026-02-28');
  await row.getByRole('button', { name: '仅标记已处理', exact: true }).click();
  await expect(row).toContainText('2026-03-31');
  await row.getByRole('button', { name: '仅标记已处理', exact: true }).click();
  await expect(row).toContainText('计划已完成');
  for (const action of await page.locator('.zc-bill-row-actions button').all()) {
    expect(await action.evaluate((node) => node.getBoundingClientRect().right <= innerWidth)).toBe(true);
  }
  await page.screenshot({ path: test.info().outputPath('bills-desktop.png'), fullPage: true });
  await row.getByRole('button', { name: '编辑', exact: true }).click();
  const edit = page.getByRole('dialog', { name: '编辑 · 账单计划', exact: true });
  await expect(edit.getByLabel(/^总期数/)).toHaveValue('3');
  await edit.getByRole('button', { name: '取消', exact: true }).click();
  await records(page).click();
  await expect(page.locator('.zc-transaction-row')).toHaveCount(1);
  await expect(page.locator('.zc-transaction-row')).toContainText('200.10');
  await page.setViewportSize({ width: 390, height: 844 });
  await go(page, 'dashboard');
  await page.getByRole('region', { name: '账单与还款', exact: true }).getByRole('button', { name: '新增账单', exact: true }).click();
  form = planForm(page);
  await form.getByLabel(/^名称/).fill('保险续费');
  await form.getByLabel(/^金额/).fill('500');
  await form.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toBeHidden();
  await page.getByRole('button', { name: '保险续费', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '账单详情', exact: true });
  await expect(detail).toContainText('不会写入收支');
  await page.screenshot({ path: test.info().outputPath('bills-mobile-detail.png') });
  await detail.getByRole('button', { name: '仅标记已处理', exact: true }).click();
  await expect(detail).toBeHidden();
  await expect(page.locator('.zc-card .zc-card')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});
