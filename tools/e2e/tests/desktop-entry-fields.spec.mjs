import { test, expect } from './fixtures.mjs';
import { openLedger } from './helpers.mjs';
import { openLedgerSection } from '../ledger-navigation.mjs';

test.use({ timezoneId: 'Asia/Shanghai' });
test.setTimeout(60_000);

for (const [width, scheme] of [[1280, 'light'], [1440, 'dark']]) {
  test(`desktop field modes and attachments stay clear at ${width}px in ${scheme}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await page.emulateMedia({ colorScheme: scheme });
    await page.clock.setFixedTime(new Date('2026-11-24T10:30:00+08:00'));
    await openLedger(page);
    await openLedgerSection(page, 'manage', 'fields');
    const settings = page.getByRole('region', { name: '记账常用字段', exact: true });
    await settings.getByRole('button', { name: '清空附加字段', exact: true }).click();
    await expect(settings.getByRole('button', { name: '清空附加字段', exact: true })).toBeEnabled();
    await settings.getByRole('checkbox', { name: '地点', exact: true }).click();
    await expect(settings.getByRole('button', { name: '清空附加字段', exact: true })).toBeEnabled();
    await page.reload();
    await openLedgerSection(page, 'manage', 'fields');
    await expect(settings.getByRole('checkbox', { name: '地点', exact: true })).toBeChecked();
    await expect(settings.getByRole('checkbox', { name: '备注', exact: true })).not.toBeChecked();
    await page.screenshot({ path: test.info().outputPath(`management-${width}.png`) });
    await openLedgerSection(page, 'transactions', 'records');
    const newEntry = page.locator('#transaction-records').getByRole('button', { name: /^\+ 记(账|支出)$/ });
    await newEntry.click();
    const form = page.getByRole('dialog', { name: '新增 · 日常收支', exact: true });
    const common = form.getByRole('button', { name: '字段模式：常用', exact: true });
    const full = form.getByRole('button', { name: '字段模式：完整', exact: true });
    const note = form.getByLabel('备注', { exact: true });
    const description = form.locator('[data-form-field$="-description"]');
    const attachment = form.locator('[data-form-field$="-attachmentDrafts"]');
    const more = form.locator('details').filter({ has: page.locator('summary').filter({ hasText: '更多字段' }) });
    await expect(common).toHaveAttribute('aria-pressed', 'true');
    await expect(full).toHaveAttribute('aria-pressed', 'false');
    await expect(form.getByText('字段显示', { exact: true })).toBeVisible();
    await expect(form.getByLabel('地点', { exact: true })).toBeVisible();
    await expect(note).toBeHidden();
    await expect(attachment).toBeVisible();
    const assertLayout = async () => {
      const heading = await form.locator('.zc-modal-header > div').first().boundingBox();
      const mode = await common.boundingBox();
      expect(Math.abs(heading.y + heading.height / 2 - mode.y - mode.height / 2)).toBeLessThanOrEqual(1);
      expect((await form.locator('.zc-modal-header').boundingBox()).height).toBeLessThanOrEqual(44);
      const descriptionBox = await description.boundingBox();
      const attachmentBox = await attachment.boundingBox();
      expect(Math.abs(descriptionBox.width - attachmentBox.width)).toBeLessThanOrEqual(1);
      expect(attachmentBox.y).toBeGreaterThanOrEqual(descriptionBox.y + descriptionBox.height);
      expect(await attachment.evaluate((node) => node.previousElementSibling?.getAttribute('data-form-field')?.endsWith('-description'))).toBe(true);
      expect(await attachment.evaluate((node) => node.closest('details') === null)).toBe(true);
      expect(await form.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
      await expect(form.getByRole('button', { name: '保存', exact: true })).toBeVisible();
    };
    await assertLayout();
    await form.getByLabel(/^金额/).fill('38.50');
    await form.getByLabel('日期', { exact: true }).fill('2026-11-23');
    await form.getByLabel('交易时间', { exact: true }).fill('08:45');
    await form.getByLabel('描述', { exact: true }).fill('电脑端字段验收');
    await form.getByRole('combobox', { name: '地点', exact: true }).fill('办公区');
    await form.getByText('新增 · 日常收支', { exact: true }).click();
    const draftStatus = form.locator('.zc-dialog-body > .zc-form-draft-status');
    await expect(draftStatus).toBeVisible();
    expect(await draftStatus.evaluate((node) => node.previousElementSibling?.tagName)).toBe('DETAILS');
    await page.screenshot({ path: test.info().outputPath(`common-${width}.png`) });
    await more.locator('summary').click();
    await note.fill('常用模式临时填写');
    await expect(common).toHaveAttribute('aria-pressed', 'true');
    await more.locator('summary').focus();
    await more.locator('summary').press('Enter');
    await expect(note).toBeHidden();
    await expect(note).toHaveValue('常用模式临时填写');
    await full.click();
    await expect(full).toHaveAttribute('aria-pressed', 'true');
    await expect(common).toHaveAttribute('aria-pressed', 'false');
    await expect(more).toHaveCount(0);
    await expect(note).toHaveValue('常用模式临时填写');
    await assertLayout();
    await attachment.locator('input[type="file"]').first().setInputFiles({ name: 'desktop-receipt.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l9sAAAAASUVORK5CYII=', 'base64') });
    await common.click();
    await expect(common).toHaveAttribute('aria-pressed', 'true');
    await expect(note).toBeHidden();
    await expect(attachment.getByText('desktop-receipt.png', { exact: true })).toBeVisible();
    await full.click();
    await expect(note).toHaveValue('常用模式临时填写');
    await form.locator('.zc-dialog-body').evaluate((node) => { node.scrollTop = 0; });
    await page.screenshot({ path: test.info().outputPath(`full-${width}.png`) });
    await form.getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: '保留草稿并关闭', exact: true }).click();
    await newEntry.click();
    await expect(common).toHaveAttribute('aria-pressed', 'true');
    await form.getByRole('button', { name: '恢复草稿', exact: true }).click();
    await expect(note).toHaveValue('常用模式临时填写');
    await expect(attachment.getByText('desktop-receipt.png', { exact: true })).toBeVisible();
    await expect(form.getByLabel('日期', { exact: true })).toHaveValue('2026-11-23');
    await expect(form.getByLabel('交易时间', { exact: true })).toHaveValue('08:45');
    await form.getByRole('button', { name: '保存', exact: true }).click();
    await expect(form).toBeHidden();
    await openLedgerSection(page, 'manage', 'fields');
    await expect(settings.getByRole('checkbox', { name: '地点', exact: true })).toBeChecked();
    await expect(settings.getByRole('checkbox', { name: '备注', exact: true })).not.toBeChecked();
  });
}
