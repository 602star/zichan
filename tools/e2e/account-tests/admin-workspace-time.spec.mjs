async function chooseDate(page, label, day) {
  await page.getByRole('button', { name: label, exact: true }).click();
  const picker = page.getByRole('dialog', { name: label, exact: true });
  await picker.getByRole('tab', { name: '年', exact: true }).click();
  await picker.getByRole('button', { name: `${day.slice(0, 4)} 年`, exact: true }).click();
  await picker.getByRole('button', { name: `${day.slice(0, 4)} 年 ${Number(day.slice(5, 7))} 月`, exact: true }).click();
  await picker.getByRole('button', { name: day, exact: true }).click();
}

